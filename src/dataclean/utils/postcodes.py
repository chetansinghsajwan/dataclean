def format_postcode(value: str, country: str | None) -> str:
    """Lay ``value`` out as ``country`` writes its postcodes.

    ``value`` is an upper-case postcode with no spaces or hyphens. Decision: a
    value that does not fit the country's pattern is returned unchanged, since a
    wrong or out-of-date pattern must not damage a good postcode. So is a value
    for an unknown country.

    Args:
        value: The postcode with spaces and hyphens removed.
        country: ISO 3166-1 alpha-2 code of the row's country, or None.

    Returns:
        The postcode in its country's layout, or ``value`` unchanged.
    """
    entry = _POSTCODES.get(country.upper()) if country else None
    if entry is None:
        return value
    layout, pattern = entry
    if "|" in layout or sum(ch in "#@" for ch in layout) != len(value):
        return value
    chars = iter(value)
    laid_out = "".join(next(chars) if ch in "#@" else ch for ch in layout)
    return laid_out if re.fullmatch(pattern, laid_out, re.IGNORECASE) else value
